/*
 * The page. Everything shown comes from the package, which is untrusted input,
 * so nothing is ever put into the page as HTML: text goes in through
 * textContent only. The page's Content-Security-Policy would block most of what
 * an injected script could do, but not injecting is the first defence.
 */
(function () {
  'use strict';
  var V = NFVerify.create(NobleNF);

  var state = { text: null, name: '', result: null, fileLines: [] };
  var $ = function (id) { return document.getElementById(id); };

  function el(tag, className, text) {
    var node = document.createElement(tag);
    if (className) { node.className = className; }
    if (text !== undefined && text !== null) { node.textContent = text; }
    return node;
  }

  function fact(list, label, value, mono) {
    if (value === undefined || value === null || value === '') { return; }
    list.appendChild(el('dt', '', label));
    list.appendChild(el('dd', mono ? 'mono' : '', String(value)));
  }

  function bytes(n) {
    if (typeof n !== 'number') { return ''; }
    if (n < 1024) { return n + ' bytes'; }
    var units = ['KB', 'MB', 'GB'], i = -1;
    do { n /= 1024; i++; } while (n >= 1024 && i < units.length - 1);
    return n.toFixed(n < 10 ? 1 : 0) + ' ' + units[i];
  }

  function banner(result, hasFingerprintCheck) {
    var box = el('div', 'banner');
    if (!result.ok) {
      box.classList.add('bad');
      box.textContent = 'This package does not verify.';
      box.appendChild(el('small', '', 'Do not rely on anything in it. The failing checks are listed below.'));
    } else if (hasFingerprintCheck) {
      box.classList.add('ok');
      box.textContent = 'Verified, and signed by the key you named.';
      box.appendChild(el('small', '', 'Unaltered since signing, and the custody chain holds. ' +
        'This shows the record is intact, not that the conclusions in it are right.'));
    } else {
      box.classList.add('warn');
      box.textContent = 'Intact — but not yet confirmed to come from the laboratory.';
      box.appendChild(el('small', '', 'The package is unaltered and its custody chain holds. ' +
        'Enter the fingerprint the laboratory gave you to confirm who signed it.'));
    }
    return box;
  }

  function renderChecks(result) {
    var list = el('ul', 'checks');
    result.checks.forEach(function (c) {
      var li = el('li');
      li.appendChild(el('span', 'tag ' + c.level, c.level.toUpperCase()));
      li.appendChild(document.createTextNode(c.text));
      list.appendChild(li);
    });
    return list;
  }

  function renderExhibit(ex) {
    var box = el('div', 'exhibit');
    box.appendChild(el('h3', '', ex.exhibit_number + (ex.original_filename ? ' — ' + ex.original_filename : '')));
    if (ex.is_demonstration_only) {
      box.appendChild(el('p', 'demo', 'Demonstration data — generated by the tool, not evidence.'));
    }
    var facts = el('dl', 'facts');
    fact(facts, 'Size', bytes(ex.file_size_bytes));
    fact(facts, 'SHA-256', ex.sha256, true);
    fact(facts, 'SHA-1', ex.sha1, true);
    fact(facts, 'MD5', ex.md5, true);
    fact(facts, 'Origin', ex.provenance_label);
    fact(facts, 'Sealed', ex.sealed_at);
    fact(facts, 'FIR', ex.fir_number);
    fact(facts, 'Station', ex.police_station);
    fact(facts, 'Seized from', ex.acquisition && ex.acquisition.seized_from);
    box.appendChild(facts);

    var certs = ex.certificates || [];
    if (certs.length) {
      box.appendChild(el('p', 'hint', 'Section 63 certificates: ' + certs.map(function (c) {
        return c.reference + (c.is_complete ? ' (both parts signed)' : ' (INCOMPLETE — a part is unsigned)');
      }).join('; ')));
    }

    var events = (ex.custody && ex.custody.events) || [];
    var table = el('table');
    var head = el('tr');
    ['#', 'Action', 'When', 'Badge', 'Detail'].forEach(function (h) { head.appendChild(el('th', '', h)); });
    table.appendChild(head);
    events.forEach(function (e) {
      var row = el('tr');
      [e.sequence, e.action, e.timestamp, e.actor_badge, e.detail].forEach(function (v) {
        row.appendChild(el('td', '', String(v)));
      });
      table.appendChild(row);
    });
    var details = el('details');
    details.appendChild(el('summary', '', 'Custody log (' + events.length + ' entries)'));
    details.appendChild(table);
    box.appendChild(details);
    return box;
  }

  function reportText() {
    var r = state.result;
    var lines = ['NetForensiq package verification', 'File: ' + state.name, ''];
    r.checks.forEach(function (c) { lines.push('[' + c.level.toUpperCase() + '] ' + c.text); });
    if (r.fingerprint) { lines.push('', 'Signing key fingerprint: ' + V.displayFingerprint(r.fingerprint)); }
    if (state.fileLines.length) { lines.push('', 'Files checked:'); state.fileLines.forEach(function (l) { lines.push('  ' + l); }); }
    lines.push('', 'Result: ' + (r.ok ? 'verified' : 'DOES NOT VERIFY'));
    return lines.join('\n');
  }

  function render() {
    var box = $('result');
    box.textContent = '';
    var r = state.result;
    if (!r) { box.hidden = true; $('filesection').hidden = true; return; }
    box.hidden = false;
    var confirmed = r.checks.some(function (c) { return c.id === 'fingerprint' && c.level === 'pass'; });
    box.appendChild(banner(r, confirmed));
    box.appendChild(el('h2', '', 'What was checked'));
    box.appendChild(renderChecks(r));

    if (r.manifest) {
      var m = r.manifest;
      if (m.case) {
        var facts = el('dl', 'facts');
        fact(facts, 'Case', m.case.case_number + (m.case.title ? ' — ' + m.case.title : ''));
        fact(facts, 'FIR', m.case.fir_number);
        fact(facts, 'Station', m.case.police_station);
        box.appendChild(facts);
      }
      var tool = m.tool || {};
      var made = el('dl', 'facts');
      fact(made, 'Made by', tool.name ? tool.name + ' ' + (tool.version || '') +
        (tool.apk_engine_version ? ', APK engine ' + tool.apk_engine_version : '') : '');
      fact(made, 'Rate table', tool.rule_base_rates_sha256, true);
      box.appendChild(made);
      (m.exhibits || []).forEach(function (ex) { box.appendChild(renderExhibit(ex)); });
    }

    var details = el('details', 'noprint');
    details.appendChild(el('summary', '', 'Plain-text report (to copy or print)'));
    var area = el('textarea');
    area.readOnly = true;
    area.value = reportText();
    details.appendChild(area);
    box.appendChild(details);
    $('filesection').hidden = !r.manifest;
  }

  function run() {
    if (state.text === null) { return; }
    state.result = V.verifyPackage(state.text, $('fp').value.trim());
    state.fileLines = [];
    $('fileresults').textContent = '';
    render();
  }

  function readText(file) {
    return file.slice(0, file.size).arrayBuffer().then(function (buf) {
      return new TextDecoder('utf-8', { fatal: false }).decode(buf);
    });
  }

  function loadPackage(file) {
    if (file.size > 64 * 1024 * 1024) {
      state.text = null; state.result = { ok: false, checks: [{ id: 'size', level: 'fail',
        text: 'this is too large to be a case package (' + bytes(file.size) + ')' }], fingerprint: null, manifest: null };
      state.name = file.name; render(); return;
    }
    readText(file).then(function (text) {
      state.text = text; state.name = file.name;
      $('pkgtext').textContent = file.name;
      run();
    });
  }

  function checkFile(file) {
    var row = el('div', 'exhibit');
    row.appendChild(el('strong', '', file.name + ' (' + bytes(file.size) + ')'));
    var bar = el('progress'); bar.max = 100; bar.value = 0;
    var status = el('p', '', 'Hashing…');
    row.appendChild(bar); row.appendChild(status);
    $('fileresults').appendChild(row);

    V.hashFile(file, function (done, total) { bar.value = Math.round(done * 100 / Math.max(total, 1)); })
      .then(function (digests) {
        row.removeChild(bar);
        var match = V.matchFile(state.result.manifest, digests);
        var line;
        if (match && match.kind === 'exhibit') {
          var extra = [];
          if (!match.sizeMatches) { extra.push('size differs from the package'); }
          if (!match.sha1Matches) { extra.push('SHA-1 differs'); }
          if (!match.md5Matches) { extra.push('MD5 differs'); }
          status.className = extra.length ? 'demo' : '';
          line = extra.length
            ? 'SHA-256 matches exhibit ' + match.exhibit.exhibit_number + ', but ' + extra.join(' and ') + '.'
            : 'This is exhibit ' + match.exhibit.exhibit_number + ': SHA-256, SHA-1, MD5 and size all match.';
        } else if (match) {
          line = 'This is the certificate PDF ' + match.certificate.reference + ' for exhibit ' +
            match.exhibit.exhibit_number + ': SHA-256 matches the one issued.';
        } else {
          status.className = 'demo';
          line = 'This file does NOT match any exhibit or certificate in the package.';
        }
        status.textContent = line;
        row.appendChild(el('p', 'mono', 'SHA-256 ' + digests.sha256));
        state.fileLines.push(file.name + ': ' + line + ' [sha256 ' + digests.sha256 + ']');
        var area = document.querySelector('#result textarea');
        if (area) { area.value = reportText(); }
      })
      .catch(function (e) { status.className = 'demo'; status.textContent = 'Could not read this file: ' + e.message; });
  }

  function wireDrop(zone, input, handler) {
    ['dragenter', 'dragover'].forEach(function (name) {
      zone.addEventListener(name, function (e) { e.preventDefault(); zone.classList.add('over'); });
    });
    ['dragleave', 'drop'].forEach(function (name) {
      zone.addEventListener(name, function (e) { e.preventDefault(); zone.classList.remove('over'); });
    });
    zone.addEventListener('drop', function (e) { Array.prototype.forEach.call(e.dataTransfer.files, handler); });
    input.addEventListener('change', function () { Array.prototype.forEach.call(input.files, handler); input.value = ''; });
  }

  wireDrop($('pkgdrop'), $('pkg'), loadPackage);
  wireDrop($('filedrop'), $('file'), checkFile);
  $('fp').addEventListener('input', run);
})();
